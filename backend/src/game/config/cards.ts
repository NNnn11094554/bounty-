/**
 * Карточки Mine — главная экономика игры. Все числа считаются из тира карточки:
 *   цена уровня n:   round(baseCost × costMultiplier^(n−1))
 *   прибыль уровня n: round(baseProfit × profitMultiplier^(n−1)) — прирост прибыли в час за этот уровень
 * Окупаемость первого уровня ≈ 4–10 ч (растёт с тиром), к 9–10 уровню переваливает за 100 ч —
 * проверка: npm run balance-check.
 *
 * Названия и описания вымышленные: никаких реальных брендов и соцсетей.
 * Иконка — "glyph/badge/palette" (см. shared/src/cards.ts).
 */
import type { CardCategory } from '@meowgul/shared';

export type CardCondition =
  | { type: 'card'; cardId: string; level: number }
  | { type: 'friends'; count: number }
  | { type: 'task'; taskId: string }
  | { type: 'league'; level: number };

