/** Цена уровня не превышает MAX_LEVEL_PRICE — числа остаются точными целыми и читаемыми. */
export const MAX_LEVEL_PRICE = 1e15;

function cappedMaxLevel(baseCost: number, costMultiplier: number, wanted: number): number {
  let level = wanted;
  while (level > 1 && baseCost * costMultiplier ** (level - 1) > MAX_LEVEL_PRICE) level--;
  return level;
}

function build(category: CardCategory, defs: Def[], limited = false): CardConfig[] {
  return defs.map((d, i) => {
    const tier = TIERS[d.tier];
    const baseCost = twoDigits(tier.cost * (d.k ?? 1));
    // небольшой разброс окупаемости внутри тира: 0.9–1.15
    const payback = tier.payback * (0.9 + ((i * 7) % 6) * 0.05);
    const costMultiplier = tier.mult[i % 3]!;
    const profitMultiplier = Math.min(1.2, Math.max(1.05, Math.round((costMultiplier / 1.48) * 100) / 100));
    return {
      id: d.id,
      category,
      nameRu: d.ru[0],
      nameEn: d.en[0],
      descRu: d.ru[1],
      descEn: d.en[1],
      icon: d.icon,
      baseCost,
      baseProfit: Math.max(1, Math.round(baseCost / payback)),
      costMultiplier,
      profitMultiplier,
      maxLevel: cappedMaxLevel(
        baseCost,
        costMultiplier,
        d.max ?? (limited ? 10 : category === 'SPECIALS' ? 20 : 25),
      ),
      cooldownSec: d.cd ?? 0,
      condition: d.cond ?? null,
      isLimited: limited,
      sortOrder: i,
    };
  });
}

