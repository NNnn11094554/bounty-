export const useAdminLocale = create<{ locale: Locale; set(locale: Locale): void }>((set) => ({
  locale: 'ru',
  set: (locale) => set({ locale }),
}));

export function useA(): (key: AdminKey, vars?: Record<string, string | number>) => string {
  const locale = useAdminLocale((s) => s.locale);
  return (key, vars) => {
    let text = (locale === 'en' ? en : ru)[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
}

